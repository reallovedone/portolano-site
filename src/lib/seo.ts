// Search and sharing helpers: head metadata values, JSON-LD, sitemap and robots.txt bodies.
// Pure functions, no I/O, so they can be unit-tested.

import { meta, REPO_URL, type FaqItem } from "../content/copy";
import { RELEASES_URL } from "./github";

/**
 * Browser chrome colours. Meta tags cannot read CSS custom properties, so these literals mirror
 * --surface-content in src/styles/tokens.css (light: :root, dark: the prefers-color-scheme block).
 * Keep them in sync when tokens.css is re-synced.
 */
export const THEME_COLOR = { light: "#ffffff", dark: "#1e1f22" } as const;

/** Open Graph image: file in public/, generated by scripts/og/generate.mjs. */
export const OG_IMAGE = { path: "/og.png", width: 1200, height: 630, alt: meta.title } as const;

export const SITE_NAME = "Portolano";
export const AUTHOR_NAME = "Simone Amato";
export const LICENSE_URL = "https://opensource.org/licenses/MIT";
export const OPERATING_SYSTEMS = "macOS 14 or later, Windows 10, Windows 11";

/** Resolves a site-relative path against the configured site URL. */
export function absoluteUrl(path: string, site: URL | string): string {
  return new URL(path, site).href;
}

export interface SoftwareApplicationInput {
  site: URL | string;
  version: string | null;
}

/**
 * schema.org SoftwareApplication for the home page.
 * Category: DeveloperApplication, because the app is a connection client for administrators and
 * developers (SSH, RDP, VNC, shells), not a general desktop utility.
 * No aggregateRating or review: there are none (and none may be invented).
 */
export function buildSoftwareApplication({ site, version }: SoftwareApplicationInput) {
  return {
    "@context": "https://schema.org",
    "@type": "SoftwareApplication",
    name: SITE_NAME,
    description: meta.description,
    applicationCategory: "DeveloperApplication",
    operatingSystem: OPERATING_SYSTEMS,
    ...(version === null ? {} : { softwareVersion: version }),
    license: LICENSE_URL,
    url: absoluteUrl("/", site),
    downloadUrl: RELEASES_URL,
    codeRepository: REPO_URL,
    sameAs: [REPO_URL],
    offers: { "@type": "Offer", price: 0, priceCurrency: "USD" },
    image: absoluteUrl(OG_IMAGE.path, site),
    author: { "@type": "Person", name: AUTHOR_NAME },
  };
}

/** schema.org FAQPage built from the visible FAQ items (same questions and answers as the page). */
export function buildFaqPage(items: readonly FaqItem[]) {
  return {
    "@context": "https://schema.org",
    "@type": "FAQPage",
    mainEntity: items.map((item) => ({
      "@type": "Question",
      name: item.q,
      acceptedAnswer: { "@type": "Answer", text: item.a },
    })),
  };
}

/** Serialises JSON-LD for an inline script; "<" is escaped so the data can never close the tag. */
export function serializeJsonLd(data: unknown): string {
  return JSON.stringify(data).replace(/</g, "\\u003c");
}

/** sitemap.xml with the home page only (the 404 page is excluded on purpose). */
export function buildSitemap(site: URL | string, lastmod: Date): string {
  const loc = absoluteUrl("/", site);
  const day = lastmod.toISOString().slice(0, 10);
  return `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
  <url>
    <loc>${loc}</loc>
    <lastmod>${day}</lastmod>
  </url>
</urlset>
`;
}

export function buildRobots(site: URL | string): string {
  return `User-agent: *
Allow: /

Sitemap: ${absoluteUrl("/sitemap.xml", site)}
`;
}
